const ease = t => 1 - Math.pow(1 - t, 3);
let last = performance.now();
function frame(now) {
  const dt = Math.min(0.05, (now - last) / 1000); last = now;
  parts.forEach(pt => {
    if (!pt.g.visible) return;
    if (pt.t < 1) pt.t = Math.min(1, pt.t + dt * 1.5);
    const k = 1 - ease(Math.max(0, pt.t)), ex = explode * pt.step * exk, gap = k * 4.5 + ex;
    pt.g.position.copy(pt.home).addScaledVector(pt.dir, gap);
    const show = pt.step === step && pt.t < 1 && gap > 0.75;
    if (pt.seams) { const sm = pt.t >= 1 && explode < 0.01 ? lineSeam : lineMat; pt.seams.forEach(w => w.material = sm); } // white only once seated
    pt.arrows.forEach(a => { a.visible = show; if (show) a.userData.stem.scale.y = Math.max(0.01, gap - 0.5); });
  });
  parts.forEach(pt => { if (!pt.g.visible) pt.arrows.forEach(a => a.visible = false); });
  const fit = fits[step], a = Math.min(1, dt * 4); // ease the view toward this step's framing
  pv.copy(fit.c).sub(controls.target).multiplyScalar(a); controls.target.add(pv); camera.position.add(pv);
  if (Math.abs(fit.v - view) > 0.001) { view += (fit.v - view) * a; resize(); }
  controls.update(); renderer.render(scene, camera); pointer(); requestAnimationFrame(frame);
}
