function buildParts() { parts = []; STEPS.forEach((st, si) => st.parts.forEach((p, pi) => {
  const g = build(p);
  const home = p.p ? new THREE.Vector3(p.p[0], p.p[2] * P, p.p[1]) : new THREE.Vector3(); // imported parts carry their own matrix
  g.position.copy(home); g.visible = false; scene.add(g);
  const dir = new THREE.Vector3(...(p.from || [0, 1, 0])).normalize();
  const pt = { g, home, dir, step: si, idx: pi, t: 1, def: p, arrows: [], box: new THREE.Box3().setFromObject(g) };
  // placement arrows: where the hovering part is going
  if (dir.y > 0.9 && !p.s) {
    const b = pt.box, z = b.max.z + 0.03, w = b.max.x - b.min.x;
    (w >= 2 ? [b.min.x + 0.5, b.max.x - 0.5] : [(b.min.x + b.max.x) / 2]).forEach(x => pt.arrows.push(makeArrow(new THREE.Vector3(x, b.min.y, z), dir)));
  } else if (dir.y > 0.9) {
    const [sx, sz] = p.s, z = home.z + sz + 0.03;
    const xs = sx >= 2 ? [home.x + 0.5, home.x + sx - 0.5] : [home.x + sx / 2];
    xs.forEach(x => pt.arrows.push(makeArrow(new THREE.Vector3(x, home.y, z), dir)));
  } else { // parts that slide in sideways get one arrow along their path, just above them
    const c = pt.box.getCenter(new THREE.Vector3()); c.y = pt.box.max.y + 0.2;
    pt.arrows.push(makeArrow(c, dir));
  }
  parts.push(pt);
})); }

// where two black parts touch, the join is drawn as a thin white line so it does not disappear
function seams() {
  scene.updateMatrixWorld(true);
  const a = new THREE.Vector3(), b = new THREE.Vector3(), q = new THREE.Vector3(), inv = new THREE.Matrix4();
  const black = parts.filter(pt => COL[pt.def.c].seam);
  black.forEach(pt => { pt.solid = []; pt.g.traverse(o => { if (o.isMesh) pt.solid.push(new THREE.Box3().setFromObject(o).expandByScalar(0.015)); }); });
  black.forEach(pt => {
    const near = black.filter(o => o !== pt && o.step <= pt.step).flatMap(o => o.solid), lines = [];
    pt.seams = []; pt.g.traverse(o => { if (o.isLineSegments) lines.push(o); });
    lines.forEach(e => {
      const pos = e.geometry.attributes.position, plain = [], seam = [];
      inv.copy(e.matrixWorld).invert();
      for (let i = 0; i < pos.count; i += 2) {
        a.fromBufferAttribute(pos, i).applyMatrix4(e.matrixWorld); b.fromBufferAttribute(pos, i + 1).applyMatrix4(e.matrixWorld);
        const n = Math.max(1, Math.ceil(a.distanceTo(b) / 0.34));
        for (let k = 0; k < n; k++) {
          q.lerpVectors(a, b, (k + 0.5) / n);
          const out = near.some(bx => bx.containsPoint(q)) ? seam : plain;
          out.push(...q.lerpVectors(a, b, k / n).applyMatrix4(inv).toArray(), ...q.lerpVectors(a, b, (k + 1) / n).applyMatrix4(inv).toArray());
        }
      }
      if (!seam.length) return;
      e.geometry = new THREE.BufferGeometry().setAttribute('position', new THREE.Float32BufferAttribute(plain, 3));
      const w = new THREE.LineSegments(new THREE.BufferGeometry().setAttribute('position', new THREE.Float32BufferAttribute(seam, 3)), lineSeam);
      w.position.copy(e.position); w.rotation.copy(e.rotation); e.parent.add(w); pt.seams.push(w);
    });
  });
}

