function makeThumbs() {
  thumbs = {};
  const c = document.createElement('canvas'); c.width = 240; c.height = 180;
  const r = new THREE.WebGLRenderer({ canvas: c, antialias: true, alpha: true });
  const cam = new THREE.OrthographicCamera(-1, 1, 1, -1, -100, 300), box = new THREE.Box3(), v = new THREE.Vector3();
  STEPS.forEach(st => st.parts.forEach(p => {
    const k = p.n + '|' + p.c; if (thumbs[k]) return;
    const sc = new THREE.Scene(); const g = build(p); sc.add(g);
    box.setFromObject(g); const ctr = box.getCenter(new THREE.Vector3());
    cam.position.copy(ctr).add(VIEWDIR); cam.lookAt(ctr); cam.updateMatrixWorld();
    let mx = 0, my = 0; // fit the projected bounding box
    for (let i = 0; i < 8; i++) {
      v.set(i & 1 ? box.max.x : box.min.x, i & 2 ? box.max.y : box.min.y, i & 4 ? box.max.z : box.min.z).applyMatrix4(cam.matrixWorldInverse);
      mx = Math.max(mx, Math.abs(v.x)); my = Math.max(my, Math.abs(v.y));
    }
    const half = Math.max(mx / (4 / 3), my, 0.8) * 1.12;
    cam.left = -half * 4 / 3; cam.right = half * 4 / 3; cam.top = half; cam.bottom = -half; cam.updateProjectionMatrix();
    r.render(sc, cam); thumbs[k] = c.toDataURL('image/png');
  }));
  r.dispose(); r.forceContextLoss();
}

// framing per step: centre and size of everything built so far, so the view follows the model
const computeFits = () => STEPS.map((_, n) => {
  const b = new THREE.Box3(); parts.forEach(pt => { if (pt.step <= n) b.union(pt.box); });
  const c = b.getCenter(new THREE.Vector3()), f = VIEWDIR.clone().normalize().negate();
  const r = new THREE.Vector3().crossVectors(f, UP).normalize(), u = new THREE.Vector3().crossVectors(r, f), q = new THREE.Vector3();
  let hw = 0, hh = 0;
  for (let i = 0; i < 8; i++) {
    q.set(i & 1 ? b.max.x : b.min.x, i & 2 ? b.max.y : b.min.y, i & 4 ? b.max.z : b.min.z).sub(c);
    hw = Math.max(hw, Math.abs(q.dot(r))); hh = Math.max(hh, Math.abs(q.dot(u)));
  }
  return { c, v: Math.max(10, hw * 2.58, hh * 3.2) };
});
