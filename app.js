function ldGeom(id) {
  if (ldGeo[id]) return ldGeo[id];
  const d = TRUCK.parts[id], v = unpack(d.v, Int16Array), ix = unpack(d.i, Uint16Array), l = unpack(d.l, Int16Array), q = 1 / TRUCK.q;
  const pos = new Float32Array(ix.length * 3), lp = new Float32Array(l.length);
  for (let i = 0; i < ix.length; i++) for (let k = 0; k < 3; k++) pos[i * 3 + k] = v[ix[i] * 3 + k] * q;
  for (let i = 0; i < l.length; i++) lp[i] = l[i] * q;
  const mesh = new THREE.BufferGeometry(); mesh.setAttribute('position', new THREE.BufferAttribute(pos, 3)); mesh.computeVertexNormals();
  const line = new THREE.BufferGeometry(); line.setAttribute('position', new THREE.BufferAttribute(lp, 3));
  return ldGeo[id] = { mesh, line };
}
function buildLd(p) {
  const g = new THREE.Group(), inner = new THREE.Group(), { mesh, line } = ldGeom(p.id), c = COL[p.c], a = p.m;
  inner.applyMatrix4(new THREE.Matrix4().set(a[0], a[1], a[2], a[9], a[3], a[4], a[5], a[10], a[6], a[7], a[8], a[11], 0, 0, 0, 1)); // rotation, 1/20 scale, position
  const me = new THREE.Mesh(mesh, mat(p)), li = new THREE.LineSegments(line, c.glass ? lineGlass : lineMat);
  if (c.glass) { me.renderOrder = 10; li.renderOrder = 11; }
  inner.add(me, li); g.add(inner); return g;
}
// cylinder or frustum lying along x (r0 at the -x end); flat = eight-sided with a flat face on top
function xCyl(r0, r1, len, seg, flat) {
  const geo = new THREE.CylinderGeometry(r0, r1, len, seg);
  if (flat) geo.rotateY(Math.PI / 8);
  geo.rotateZ(Math.PI / 2); return geo;
}
function zCyl(r, len, seg) { const geo = new THREE.CylinderGeometry(r, r, len, seg); geo.rotateX(Math.PI / 2); return geo; }


