function pointer() {
  const path = $('lead'), stage = $('stage').getBoundingClientRect(), co = $('callout').getBoundingClientRect();
  box3.makeEmpty(); parts.forEach(pt => { if (pt.step === step && pt.g.visible) box3.expandByObject(pt.g); });
  if (box3.isEmpty() || !co.width) { path.setAttribute('d', ''); return; }
  let maxX = -1e9, minX = 1e9, minY = 1e9, maxY = -1e9;
  for (let i = 0; i < 8; i++) {
    pv.set(i & 1 ? box3.max.x : box3.min.x, i & 2 ? box3.max.y : box3.min.y, i & 4 ? box3.max.z : box3.min.z).project(camera);
    const x = (pv.x + 1) / 2 * stage.width, y = (1 - pv.y) / 2 * stage.height;
    maxX = Math.max(maxX, x); minX = Math.min(minX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y);
  }
  const cx = co.left - stage.left + co.width / 2, cb = co.bottom - stage.top, ty = (minY + maxY) / 2, tx = maxX + 14;
  const cl = co.left - stage.left, cm = co.top - stage.top + co.height / 2, mid = (minX + maxX) / 2;
  // is the rest of the model in the way on the right? then come in from above instead
  pv.copy(controls.target).project(camera);
  const blocked = maxX < (pv.x + 1) / 2 * stage.width - 40;
  let d = '';
  if (blocked && mid < cl - 24 && minY - 14 > cm + 24) d = `M${cl} ${cm}H${mid}V${minY - 14}`;
  else if (ty > cb + 24 && tx < cx - 24) d = `M${cx} ${cb}V${ty}H${tx}`;
  else if (minY - 14 > cb + 24) d = `M${cx} ${cb}V${minY - 14}`;
  path.setAttribute('d', d);
}
